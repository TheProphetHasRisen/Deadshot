# -*- coding: utf-8 -*-
"""Write season2026_yahoo.py from the raw Yahoo pull, in exactly the shapes season2026.py uses.

    python3 yahoo_fetch.py 2026 && python3 yahoo_to_2026.py

season2026.py was typed from Brian's screenshots; on 15 Oct 2026 every game, draft pick, add,
drop and trade in it was checked against Yahoo and matched. It now imports this file at the
bottom, so Yahoo's numbers replace the typed ones wherever Yahoo has them, and the typed file
stays as the fallback (and for the contested waiver claims, which Yahoo's API does not list).

Times are written in US Eastern, as Yahoo's own pages and Brian's screenshots show them.
"""
import datetime as dt, pprint
from zoneinfo import ZoneInfo
import yahoo_parse as P

ET = ZoneInfo('America/New_York')
YEAR = 2026

def et(ts):
    t = dt.datetime.fromtimestamp(ts, ET)
    return t.strftime('%b ') + str(t.day), t.strftime('%I:%M %p').lstrip('0').lower()

def standings():
    out = {}
    lg = P.load(YEAR, 'standings')['league'][1]['standings'][0]['teams']
    T = P.teams(YEAR)
    for t in P.items(lg):
        f = P.flat(t['team'][0]); st = t['team'][2]['team_standings']
        o = st['outcome_totals']; sk = st.get('streak') or {}
        out[T[f['team_key']]['name']] = (int(st['rank']), int(o['wins']), int(o['losses']), int(o['ties']),
            round(float(st['points_for']), 2), round(float(st['points_against']), 2),
            ('W' if sk.get('type') == 'win' else 'L' if sk.get('type') == 'loss' else 'T') + str(sk.get('value', 0)),
            int(f.get('waiver_priority') or 0), int(f.get('number_of_moves') or 0))
    return out

def main():
    G = P.games(YEAR)
    W = [(g['wk'], g['ta'], g['aa'], g['pa'], g['tb'], g['ab'], g['pb'], '') for g in G if g['status'] == 'postevent']
    nxt = min((g['wk'] for g in G if g['status'] != 'postevent'), default=None)
    UP = {nxt: [(g['ta'], g['pa'], g['tb'], g['pb']) for g in G if g['wk'] == nxt]} if nxt else {}
    moves, trades, times, tpos = [], [], {}, {}
    for t in P.transactions(YEAR):
        if t['status'] != 'successful': continue
        d, hm = et(t['ts'])
        if t['kind'] in ('add', 'drop', 'add/drop'):
            team = next(p['to'] if p['move'] == 'add' else p['frm'] for p in t['players'])
            adds = [(p['n'], p['nfl'], p['pos'], 'W' if p['source'] == 'waivers' else 'FA') for p in t['players'] if p['move'] == 'add']
            drops = [(p['n'], p['nfl'], p['pos']) for p in t['players'] if p['move'] == 'drop']
            moves.append((d, hm, team, adds, drops))
        elif t['kind'] == 'trade':
            sides = {}
            for p in t['players']:
                sides.setdefault(p['to'], []).append(p['n']); tpos[p['n']] = p['pos']
            (ta, ga), (tb, gb) = list(sides.items())
            trades.append((d, ta, ga, tb, gb)); times.setdefault(d, hm)
    moves.reverse()   # newest first, as Yahoo lists them and as season2026.py was typed
    ro = [(r['wk'], r['team'], r['n'], r['pos'], r['slot'], r['pts']) for r in P.rosters(YEAR)]
    body = [
        '# -*- coding: utf-8 -*-',
        '"""GENERATED by yahoo_to_2026.py from Yahoo. Do not edit: re-run it. See season2026.py."""',
        'W2026 = ' + pprint.pformat(W, width=110),
        'UPCOMING2026 = ' + pprint.pformat(UP, width=110),
        'STANDINGS2026_WK5 = ' + pprint.pformat(standings(), width=110),
        'MOVES2026 = ' + pprint.pformat(moves, width=140),
        'TRADES2026 = ' + pprint.pformat(trades, width=140),
        'TRADETIMES = ' + pprint.pformat(times),
        'TRADEPOS = ' + pprint.pformat(tpos),
        '# every player on every roster every week: (week, team, player, position, slot, points);',
        '# slot BN is the bench and IR injured reserve, anything else started',
        'ROSTERS2026 = ' + pprint.pformat(ro, width=120),
    ]
    open('season2026_yahoo.py', 'w').write('\n'.join(body) + '\n')
    print('wrote season2026_yahoo.py: %d games, next week %s, %d moves, %d trades, %d roster rows'
          % (len(W), nxt, len(moves), len(trades), len(ro)))

if __name__ == '__main__':
    main()
